import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import sharp from 'sharp';
import fs from 'fs/promises';
import path from 'path';
import os from 'os';
import { resetPhotoStorageCache } from '@/lib/photo-storage';
import {
  processPersonImage,
  savePersonImageFiles,
  readPersonImageFile,
  deletePersonImageFiles,
  deletePersonImageDir,
  getPersonImageDir,
} from '@/lib/person-image-storage';

async function makeJpeg(width: number, height: number): Promise<Buffer> {
  return sharp({ create: { width, height, channels: 3, background: { r: 200, g: 100, b: 50 } } })
    .jpeg()
    .toBuffer();
}

async function makeTransparentPng(width: number, height: number): Promise<Buffer> {
  return sharp({ create: { width, height, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .png()
    .toBuffer();
}

describe('person-image-storage', () => {
  let tmpDir: string;
  const originalEnv = process.env.PHOTO_STORAGE_PATH;

  beforeEach(async () => {
    tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'person-images-'));
    process.env.PHOTO_STORAGE_PATH = tmpDir;
    resetPhotoStorageCache();
  });

  afterEach(async () => {
    process.env.PHOTO_STORAGE_PATH = originalEnv;
    resetPhotoStorageCache();
    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  describe('processPersonImage', () => {
    it('scales large images down to 2560px on the long side and keeps the aspect ratio', async () => {
      const result = await processPersonImage(await makeJpeg(4000, 2000));
      expect(result.ext).toBe('jpg');
      expect(result.width).toBe(2560);
      expect(result.height).toBe(1280);
      const thumbMeta = await sharp(result.thumbnail).metadata();
      expect(thumbMeta.width).toBe(400);
      expect(thumbMeta.height).toBe(400);
    });

    it('never upscales small images', async () => {
      const result = await processPersonImage(await makeJpeg(120, 80));
      expect(result.width).toBe(120);
      expect(result.height).toBe(80);
    });

    it('keeps transparent images as PNG', async () => {
      const result = await processPersonImage(await makeTransparentPng(50, 50));
      expect(result.ext).toBe('png');
    });

    it('rejects non-image data', async () => {
      await expect(processPersonImage(Buffer.from('not an image at all'))).rejects.toThrow('Unsupported image format');
    });
  });

  describe('files on disk', () => {
    it('stores files under {base}/{userId}/gallery/{personId} and reads them back', async () => {
      const processed = await processPersonImage(await makeJpeg(300, 200));
      const files = await savePersonImageFiles('user1', 'person1', 'abc123', processed);

      expect(files).toEqual({ filename: 'abc123.jpg', thumbnail: 'abc123_thumb.jpg' });
      expect(getPersonImageDir('user1', 'person1')).toBe(path.join(tmpDir, 'user1', 'gallery', 'person1'));

      const read = await readPersonImageFile('user1', 'person1', 'abc123.jpg');
      expect(read?.mimeType).toBe('image/jpeg');
      expect(read?.buffer.equals(processed.full)).toBe(true);
    });

    it('refuses filenames that are not generated by the app', async () => {
      expect(await readPersonImageFile('user1', 'person1', '../../etc/passwd')).toBeNull();
      expect(await readPersonImageFile('user1', 'person1', 'abc.svg')).toBeNull();
    });

    it('rejects ids that would produce unsafe filenames', async () => {
      const processed = await processPersonImage(await makeJpeg(10, 10));
      await expect(savePersonImageFiles('user1', 'person1', '../x', processed)).rejects.toThrow();
    });

    it('rejects person ids that escape the storage directory', () => {
      expect(() => getPersonImageDir('user1', '../../..')).toThrow();
    });

    it('deletes single files and whole folders', async () => {
      const processed = await processPersonImage(await makeJpeg(30, 30));
      await savePersonImageFiles('user1', 'person1', 'a1', processed);
      await savePersonImageFiles('user1', 'person1', 'b2', processed);

      await deletePersonImageFiles('user1', 'person1', ['a1.jpg', 'a1_thumb.jpg']);
      const remaining = await fs.readdir(getPersonImageDir('user1', 'person1'));
      expect(remaining.sort()).toEqual(['b2.jpg', 'b2_thumb.jpg']);

      await deletePersonImageDir('user1', 'person1');
      await expect(fs.stat(getPersonImageDir('user1', 'person1'))).rejects.toThrow();
    });
  });
});
